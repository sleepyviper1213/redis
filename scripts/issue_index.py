#!/usr/bin/env python3
"""Write one issue index per feature from the repository's GitHub issues.

An issue belongs to a feature through its `feat:<folder>` label, where <folder>
is a folder in docs/features/. Its type comes from its other labels, and its
requirement from the body: either `**Requirement:** FR-006.8` or a
`## Requirement` heading followed by the IDs on its first line. A range such as
`FR-006.1 to FR-006.11` is listed by its two ends.

    gh issue list --state all --limit 1000 \
        --json number,title,state,labels,body,url > issues.json
    scripts/issue_index.py issues.json

Rewrites docs/features/<folder>/issues.md for every feature that has an issue,
and removes it for a feature that has none. The output depends only on the
issues, so a run that changes nothing leaves the files as they were.
"""

import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
FEATURES = ROOT / "docs" / "features"
FEATURE_LABEL = "feat:"

# Label to type, first match in this order wins. Anything else is "Other".
TYPES = [
    ("epic", "Epic"),
    ("risk", "Risk"),
    ("bug", "Bug"),
    ("enhancement", "Feature"),
    ("spike", "Spike"),
    ("task", "Task"),
    ("documentation", "Docs"),
]

# "**Requirement:** FR-006.8, NFR-010.1" reads the rest of its line; a
# "## Requirement" heading reads the lines under it, up to a blank line or the
# next heading.
REQUIREMENT = re.compile(
    r"\*\*Requirements?:?\*\*:?[ \t]*(?P<line>[^\r\n]*)"
    r"|^#+[ \t]*Requirements?[ \t]*\r?\n(?P<block>(?:[^\r\n#][^\r\n]*\r?\n?)*)",
    re.IGNORECASE | re.MULTILINE,
)
ID = re.compile(r"\b(?:NFR|FR|BR)-\d{3}(?:\.\d+)?\b")


def label_names(issue):
    return [label["name"] for label in issue["labels"]]


def issue_type(labels):
    for label, name in TYPES:
        if label in labels:
            return name
    return "Other"


def first_line(block):
    """The first non-empty line of the block: the IDs, before any explanation."""
    return next((line for line in (block or "").splitlines() if line.strip()), "")


def requirements(body):
    """The requirement IDs named in an issue body, in order, without repeats."""
    found = []
    for match in REQUIREMENT.finditer(body or ""):
        text = match.group("line") or first_line(match.group("block"))
        for requirement in ID.findall(text):
            if requirement not in found:
                found.append(requirement)
    # "FR-006" names the group when "FR-006.1" is given: keep the specific ID.
    return [r for r in found if not any(o.startswith(r + ".") for o in found)]


def cell(text):
    return text.replace("|", "\\|").replace("\r", " ").replace("\n", " ").strip()


def render(feature, issues):
    lines = [
        f"# Issues: {feature}",
        "",
        "Generated by `scripts/issue_index.py` from the issues labelled "
        f"`{FEATURE_LABEL}{feature}`. Do not edit; change the issue instead.",
        "",
        "| Issue | Type | Title | Requirement | State |",
        "|-------|------|-------|-------------|-------|",
    ]
    for issue in sorted(issues, key=lambda i: i["number"]):
        number = issue["number"]
        lines.append(
            "| [#{n}]({url}) | {kind} | {title} | {req} | {state} |".format(
                n=number,
                url=issue["url"],
                kind=issue_type(label_names(issue)),
                title=cell(issue["title"]),
                req=cell(", ".join(requirements(issue["body"]))) or "none",
                state=issue["state"].lower(),
            )
        )
    return "\n".join(lines) + "\n"


def group_by_feature(issues):
    grouped = {}
    for issue in issues:
        for name in label_names(issue):
            if name.startswith(FEATURE_LABEL):
                grouped.setdefault(name[len(FEATURE_LABEL):], []).append(issue)
    return grouped


def main(argv):
    if len(argv) != 2:
        print(__doc__, file=sys.stderr)
        return 2
    issues = json.loads(Path(argv[1]).read_text(encoding="utf-8"))
    grouped = group_by_feature(issues)

    status = 0
    for feature, members in sorted(grouped.items()):
        folder = FEATURES / feature
        if not folder.is_dir():
            print(f"no docs/features/{feature}/ for label "
                  f"{FEATURE_LABEL}{feature}", file=sys.stderr)
            status = 1
            continue
        (folder / "issues.md").write_text(render(feature, members),
                                          encoding="utf-8", newline="\n")
    for index in FEATURES.glob("*/issues.md"):
        if index.parent.name not in grouped:
            index.unlink()
    return status


if __name__ == "__main__":
    sys.exit(main(sys.argv))
